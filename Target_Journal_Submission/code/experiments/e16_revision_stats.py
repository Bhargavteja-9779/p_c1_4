"""E16 (revision): descriptive and sensitivity statistics requested in review, computed from stored results only.

Inputs : results/raw/e12_nights_<stager>.csv.gz (per-night primary-protocol outputs; regenerated by E12, git-ignored),
         results/raw/e12_honest_<stager>.csv.gz, results/raw/e16_plainsplit_<stager>.csv.gz (E16 plain-split run),
         results/statistics/e15_local.csv, results/summaries/<stager>_xfit.csv
Outputs: results/statistics/e16_decisions_calibrated.csv   decisions with calibrated baselines (pooled and per cohort)
         results/statistics/e16_local_risk_theory.csv      observed vs finite-sample-theory risk of site coverage < 0.80
         results/statistics/e16_plainsplit_vs_primary.csv  coverage / width, plain-split vs primary design
         results/statistics/e16_descriptives.csv           TST half-widths, coverage by width tercile, prevalence, WASO window
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy import stats

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.utils import RESULTS_DIR  # noqa: E402

STAGERS = ["yasa", "lgbm_sc_s0"]
S, RAW = RESULTS_DIR / "statistics", RESULTS_DIR / "raw"
THRESH = {"TST": ("<", 360), "SOL": (">", 30), "WASO": (">", 30), "REML": ("<=", 15)}
DEC_METHODS = ["norm_reg_ffbs", "scp_signed", "ba_loa", "scp_abs_cal", "scp_abs_bc"]


def _side(op, x, thr):
    return {"<": x < thr, ">": x > thr, "<=": x <= thr}[op]


def decisions_calibrated():
    rows = []
    for st in STAGERS:
        n = pd.read_csv(RAW / f"e12_nights_{st}.csv.gz")
        n = n[n.setting == "within"]
        for p, (op, thr) in THRESH.items():
            g = n[(n.param == p) & n.method.isin(DEC_METHODS)]
            ref = _side(op, g.y, thr)
            pos = {"<": g.hi < thr, ">": g.lo > thr, "<=": g.hi <= thr}[op]
            neg = {"<": g.lo >= thr, ">": g.hi <= thr, "<=": g.lo > thr}[op]
            conf = pos | neg
            ok = (pos & ref) | (neg & ~ref)
            d = g.assign(ref=ref, conf=conf, ok=ok, raw_ok=(_side(op, g.plug, thr) == ref),
                         cal_ok=(_side(op, g.plugc, thr) == ref))
            for coh_label, dd in [("pooled", d)] + [(c, x) for c, x in d.groupby("cohort")]:
                for m, x in dd.groupby("method"):
                    c = x[x.conf]
                    u = x[~x.conf]
                    rows.append(dict(stager=st, cohort=coh_label, param=p, method=m, n=len(x), prevalence=x.ref.mean(),
                                     frac_decided=x.conf.mean(), acc_decided=c.ok.mean() if len(c) else np.nan,
                                     raw_plugin_acc_all=x.raw_ok.mean(), cal_plugin_acc_all=x.cal_ok.mean(),
                                     raw_plugin_acc_decided=c.raw_ok.mean() if len(c) else np.nan,
                                     cal_plugin_acc_decided=c.cal_ok.mean() if len(c) else np.nan,
                                     cal_plugin_acc_undecided=u.cal_ok.mean() if len(u) else np.nan))
    pd.DataFrame(rows).to_csv(S / "e16_decisions_calibrated.csv", index=False)


def local_risk_theory(alpha=0.10, thresh=0.80):
    """P(realised coverage of N test nights < thresh) for an exchangeable split-conformal interval.
    Coverage given the calibration set ~ Beta(n+1-l, l), l = floor(alpha (n+1)); test nights ~ Binomial(N, C)."""
    loc = pd.read_csv(S / "e15_local.csv")
    rows = []
    for st in STAGERS:
        h = pd.read_csv(RAW / f"e12_honest_{st}.csv.gz")
        h = h[(h.setting == "local") & (h.method == "norm_reg_ffbs")]
        nt = h.groupby(["cohort", "n_target"]).n_test.median()
        for (coh, n), N in nt.items():
            N = int(N)
            l = int(np.floor(alpha * (n + 1)))
            kmax = int(np.ceil(thresh * N)) - 1                      # realised coverage < thresh  <=>  hits <= kmax
            a, b = n + 1 - l, l
            theory = float(stats.betabinom.cdf(kmax, N, a, b))
            sel = loc[(loc.stager == st) & (loc.cohort == coh) & (loc.n_target == n)]
            row = dict(stager=st, cohort=coh, n_cal=n, n_test_median=N, theory_p_lt80=theory)
            for m in ["norm_reg_ffbs", "scp_abs_cal", "scp_abs_bc", "ba_loa"]:
                s = sel[sel.method == m]
                row[f"obs_{m}"] = float(s.p_cov_lt80.median()) if len(s) else np.nan
            rows.append(row)
    pd.DataFrame(rows).to_csv(S / "e16_local_risk_theory.csv", index=False)


def plainsplit():
    rows = []
    for st in STAGERS:
        f = RAW / f"e16_plainsplit_{st}.csv.gz"
        if not f.exists():
            continue
        ps = pd.read_csv(f)
        pr = pd.read_csv(RAW / f"e12_honest_{st}.csv.gz")
        pr = pr[pr.setting == "within"]
        for m in ["norm_reg_ffbs", "scp_signed", "ba_loa", "ba_reg"]:
            a = ps[ps.method == m].groupby(["cohort", "param"]).agg(cov_plain=("coverage", "mean"), width_plain=("mean_width", "mean"),
                                                                    is_plain=("interval_score", "mean"), n_cal_plain=("n_cal", "median"))
            b = pr[pr.method == m].groupby(["cohort", "param"]).agg(cov_primary=("coverage", "mean"), width_primary=("mean_width", "mean"),
                                                                    is_primary=("interval_score", "mean"), n_cal_primary=("n_cal", "median"))
            j = a.join(b).reset_index()
            j.insert(0, "method", m)
            j.insert(0, "stager", st)
            rows.append(j)
    if rows:
        out = pd.concat(rows)
        out["width_ratio"] = out.width_plain / out.width_primary
        out.to_csv(S / "e16_plainsplit_vs_primary.csv", index=False)


def descriptives():
    rows = []
    for st in STAGERS:
        n = pd.read_csv(RAW / f"e12_nights_{st}.csv.gz")
        n = n[n.setting == "within"]
        t = n[n.param == "TST"]
        for m in ["norm_reg_ffbs", "scp_signed", "scp_abs_cal"]:
            for c, g in t[t.method == m].groupby("cohort"):
                rows.append(dict(stager=st, kind="tst_halfwidth_median", cohort=c, method=m, value=float((g.hi - g.lo).median() / 2)))
        for c, g in t[t.method == "norm_reg_ffbs"].groupby("cohort"):
            w = g.width.values
            q = np.quantile(w, [1 / 3, 2 / 3])
            terc = np.digitize(w, q)
            for k, name in enumerate(["narrow", "middle", "wide"]):
                rows.append(dict(stager=st, kind="tst_coverage_by_width_tercile", cohort=c, method="norm_reg_ffbs", tercile=name,
                                 value=float(g.covered.values[terc == k].mean())))
        for p, (op, thr) in THRESH.items():
            u = n[(n.param == p) & (n.method == "norm_reg_ffbs")].drop_duplicates(["cohort", "night"])
            for c, g in u.groupby("cohort"):
                rows.append(dict(stager=st, kind="n_positive_nights", cohort=c, param=p, value=int(_side(op, g.y, thr).sum()), n=len(g)))
    # WASO window (SC): wake after the final awakening and WASO if that wake were counted
    s = pd.read_csv(RESULTS_DIR / "summaries" / "yasa_xfit.csv")
    for c, g in s.groupby("cohort"):
        win = g.n_epochs * 0.5
        post = win - g.ref_SOL - g.ref_WASO - g.ref_TST
        rows.append(dict(stager="ref", kind="waso_postwake_median", cohort=c, value=float(post.median())))
        rows.append(dict(stager="ref", kind="waso_incl_postwake_median", cohort=c, value=float((g.ref_WASO + post).median())))
        rows.append(dict(stager="ref", kind="waso_median", cohort=c, value=float(g.ref_WASO.median())))
    pd.DataFrame(rows).to_csv(S / "e16_descriptives.csv", index=False)


if __name__ == "__main__":
    decisions_calibrated()
    local_risk_theory()
    plainsplit()
    descriptives()
    print("E16 revision statistics written to", S)
